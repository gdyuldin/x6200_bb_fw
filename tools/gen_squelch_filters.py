#!/usr/bin/env python3
"""
Generate squelch metric filters for the x6200 SDR firmware.

The squelch module measures a per-mode "signal vs noise" metric and needs two
kinds of fixed filters:

  * SSB: two equal-width band-pass filters, 300..700 Hz and 1300..1700 Hz at the
    12 kHz demod rate. Their peaks give the low/high band levels used for the
    spectral-slope term and the in-band SNR term.
  * NBFM: a 3.5 kHz high-pass at the 48 kHz discriminator rate, measuring the
    out-of-band (above voice) noise.

All filters are 4th order (two CMSIS DF1 biquads). The script writes a C header
(default: App/SDR/sdr_squelch_filters.h). Coefficients are Butterworth (flat
passband) with the CMSIS DF1 layout {b0, b1, b2, a1, a2}; the biquad recurrence
is

    y[n] = b0*x[n] + b1*x[n-1] + b2*x[n-2] + a1*y[n-1] + a2*y[n-2]

so the feedback coefficients are stored negated relative to the scipy/MATLAB
denominator (which is a0 + a1*z^-1 + a2*z^-2).
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
from scipy import signal

DEFAULT_OUTPUT = Path(__file__).resolve().parent.parent / "App/SDR/sdr_squelch_filters.h"

SSB_FS_HZ = 12000.0
SSB_LOW_HZ = (300.0, 700.0)
SSB_HIGH_HZ = (1300.0, 1700.0)
SSB_ORDER = 2  # band-pass order 2 -> 2 biquads, overall 4th order

FM_FS_HZ = 48000.0
FM_HPF_HZ = 3500.0
FM_ORDER = 4  # high-pass order 4 -> 2 biquads


def format_float(value: float) -> str:
    text = f"{float(value):.9g}"
    if "." not in text and "e" not in text and "E" not in text:
        text += ".0"
    return text + "f"


def format_array(values: np.ndarray, indent: str = "    ") -> str:
    return ",\n".join(indent + format_float(v) for v in values) + ","


def sos_to_df1(sos: np.ndarray) -> np.ndarray:
    """Convert a scipy sos array to the CMSIS DF1 {b0,b1,b2,a1,a2} layout.

    CMSIS stores the feedback coefficients with the sign of the recurrence
    y[n] = ... + a1*y[n-1] + a2*y[n-2], so scipy's denominator a1/a2 must be
    negated (otherwise the poles are mirrored outside the unit circle).
    """
    if sos.shape[1] != 6:
        raise ValueError("sos must have 6 columns")
    coeffs = np.empty((sos.shape[0], 5), dtype=float)
    for i, (b0, b1, b2, a0, a1, a2) in enumerate(sos):
        if a0 == 0.0:
            raise ValueError("a0 is zero")
        coeffs[i] = (b0 / a0, b1 / a0, b2 / a0, -a1 / a0, -a2 / a0)
    return coeffs


def design_ssb(fs_hz: float, band_hz: tuple[float, float]) -> np.ndarray:
    sos = signal.butter(SSB_ORDER, band_hz, btype="bandpass", fs=fs_hz,
                        output="sos")
    return sos_to_df1(sos)


def design_fm_hpf(fs_hz: float, f_hz: float) -> np.ndarray:
    sos = signal.butter(FM_ORDER, f_hz, btype="highpass", fs=fs_hz,
                        output="sos")
    return sos_to_df1(sos)


def flat_array(coeffs: np.ndarray) -> np.ndarray:
    return coeffs.reshape(-1)


def build_header(ssb_low: np.ndarray, ssb_high: np.ndarray,
                 fm_hpf: np.ndarray) -> str:
    lines = [
        "#pragma once",
        "",
        "/*",
        " * Squelch metric filter coefficients.",
        " * Generated by tools/gen_squelch_filters.py. Do not edit by hand.",
        " *",
        " * CMSIS DF1 biquad layout {b0, b1, b2, a1, a2}:",
        " *   y[n] = b0*x[n] + b1*x[n-1] + b2*x[n-2] + a1*y[n-1] + a2*y[n-2]",
        " */",
        "",
        "/*",
        f" * SSB low band  : {SSB_LOW_HZ[0]:g} .. {SSB_LOW_HZ[1]:g} Hz "
        f"at {SSB_FS_HZ:g} Hz",
        f" * SSB high band : {SSB_HIGH_HZ[0]:g} .. {SSB_HIGH_HZ[1]:g} Hz "
        f"at {SSB_FS_HZ:g} Hz",
        " * Both band-pass, 4th order (2 biquads).",
        " */",
        f"#define SDR_SQUELCH_SSB_LOW_STAGES {ssb_low.shape[0]}u",
        f"#define SDR_SQUELCH_SSB_HIGH_STAGES {ssb_high.shape[0]}u",
        "",
        "static const float sdr_squelch_ssb_low_coeffs"
        "[SDR_SQUELCH_SSB_LOW_STAGES * 5] = {",
        format_array(flat_array(ssb_low)),
        "};",
        "",
        "static const float sdr_squelch_ssb_high_coeffs"
        "[SDR_SQUELCH_SSB_HIGH_STAGES * 5] = {",
        format_array(flat_array(ssb_high)),
        "};",
        "",
        "/*",
        f" * NBFM HPF : {FM_HPF_HZ:g} Hz at {FM_FS_HZ:g} Hz,"
        " 4th order (2 biquads).",
        " */",
        f"#define SDR_SQUELCH_FM_HPF_STAGES {fm_hpf.shape[0]}u",
        "",
        "static const float sdr_squelch_fm_hpf_coeffs"
        "[SDR_SQUELCH_FM_HPF_STAGES * 5] = {",
        format_array(flat_array(fm_hpf)),
        "};",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    ssb_low = design_ssb(SSB_FS_HZ, SSB_LOW_HZ)
    ssb_high = design_ssb(SSB_FS_HZ, SSB_HIGH_HZ)
    fm_hpf = design_fm_hpf(FM_FS_HZ, FM_HPF_HZ)

    print(f"SSB low  {SSB_LOW_HZ}: {ssb_low.shape[0]} biquads")
    print(f"SSB high {SSB_HIGH_HZ}: {ssb_high.shape[0]} biquads")
    print(f"FM HPF   {FM_HPF_HZ:g} Hz: {fm_hpf.shape[0]} biquads")

    DEFAULT_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    DEFAULT_OUTPUT.write_text(build_header(ssb_low, ssb_high, fm_hpf),
                              encoding="utf-8")
    print(f"Wrote {DEFAULT_OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
